"""
L&D Operations Copilot — Email Sender

Sends the generated daily brief via Gmail API (OAuth).
Uses the same OAuth credentials as Gmail reader — no extra setup.
"""

import base64
import logging
from datetime import datetime, timedelta, timezone
from email.mime.text import MIMEText
from email.mime.multipart import MIMEMultipart

from src.auth import get_gmail_service
from src.config import get_config

logger = logging.getLogger(__name__)

# IST timezone
IST = timezone(timedelta(hours=5, minutes=30))


async def send_brief_email(brief_html: str, metadata: dict | None = None) -> dict:
    """
    Send the daily brief as an HTML email to the configured user.

    Args:
        brief_html: The HTML content of the brief
        metadata: Optional metadata to include in the email footer

    Returns:
        dict with keys: success (bool), message_id (str), error (str or None)
    """
    config = get_config()
    service = get_gmail_service()

    today = datetime.now(IST).strftime("%A, %B %d, %Y")
    subject = f"🌅 L&D Morning Brief — {today}"

    logger.info("Sending daily brief email to %s", config.user_email)

    try:
        # Build MIME message
        message = MIMEMultipart("alternative")
        message["To"] = config.user_email
        message["From"] = config.user_email  # Sending to self
        message["Subject"] = subject

        # Plain text fallback
        plain_text = (
            f"L&D Operations Copilot — Daily Brief for {today}\n\n"
            "This email is best viewed in HTML format.\n"
            "Open it in Gmail or another HTML-capable email client."
        )
        message.attach(MIMEText(plain_text, "plain"))

        # HTML content with wrapper
        full_html = _wrap_html(brief_html, today, metadata)
        message.attach(MIMEText(full_html, "html"))

        # Encode and send
        raw_message = base64.urlsafe_b64encode(
            message.as_bytes()
        ).decode("utf-8")

        sent = (
            service.users()
            .messages()
            .send(userId="me", body={"raw": raw_message})
            .execute()
        )

        message_id = sent.get("id", "unknown")
        logger.info("Brief email sent successfully (Message ID: %s)", message_id)

        return {
            "success": True,
            "message_id": message_id,
            "error": None,
        }

    except Exception as e:
        logger.error("Failed to send brief email: %s", e, exc_info=True)
        return {
            "success": False,
            "message_id": None,
            "error": str(e),
        }


def _wrap_html(brief_html: str, date_str: str, metadata: dict | None) -> str:
    """Wrap the Gemini-generated HTML in a proper email document structure."""

    gen_time = ""
    if metadata:
        gen_time = f"""
        <p style="margin: 4px 0;">
            ⏱ Generated in {metadata.get('generation_time_seconds', '?')}s
            (Fetch: {metadata.get('fetch_time_seconds', '?')}s,
             AI: {metadata.get('gemini_time_seconds', '?')}s)
        </p>
        """

        errors = metadata.get("errors", {})
        if errors:
            error_lines = "".join(
                f"<li>⚠️ {source}: {err}</li>"
                for source, err in errors.items()
            )
            gen_time += f"""
            <div style="background: #fff3cd; padding: 8px 12px; border-radius: 4px; margin-top: 8px;">
                <strong>Data Source Warnings:</strong>
                <ul style="margin: 4px 0; padding-left: 20px;">{error_lines}</ul>
            </div>
            """

    return f"""<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>L&D Morning Brief — {date_str}</title>
</head>
<body style="margin: 0; padding: 0; background-color: #f0f2f5; font-family: 'Google Sans', Arial, sans-serif;">
    <div style="max-width: 700px; margin: 0 auto; padding: 20px;">
        {brief_html}

        <div style="margin-top: 32px; padding-top: 16px; border-top: 1px solid #e0e0e0; text-align: center; color: #9aa0a6; font-size: 12px;">
            <p style="margin: 4px 0;">
                🤖 Generated by <strong>L&D Operations Copilot</strong>
            </p>
            {gen_time}
            <p style="margin: 4px 0;">
                Powered by Gemini 2.5 Flash · Cloud Run · GitHub Actions
            </p>
        </div>
    </div>
</body>
</html>"""
